import type { Reader } from "../../reader/reader.js";
import { mentionTokens } from "../../validate/validators.js";
import { mapCodeSpans } from "../studio/pages/code-spans.js";

export function noteName(id: string): string {
  return id.replace(":", ".");
}
export function notePath(id: string): string {
  const [namespace, path = ""] = id.split(":");
  if (namespace === "spec") return `sdp/specs/${path.split(".")[0] ?? path}/${noteName(id)}.md`;
  if (namespace === "pack") return `sdp/packs/${noteName(id)}.md`;
  return `sdp/code/${namespace ?? ""}/${noteName(id)}.md`;
}
export function termPath(id: string, key: string): string {
  return `sdp/terms/term.${id.slice(5)}.${key}.md`;
}
export const code = (value: string): string => {
  const runs = [...value.matchAll(/`+/gu)].map((m) => m[0].length);
  const fence = "`".repeat(Math.max(0, ...runs) + 1);
  return `${fence}${value.startsWith("`") || value.endsWith("`") ? " " : ""}${value}${value.startsWith("`") || value.endsWith("`") ? " " : ""}${fence}`;
};
export function escapeText(text: string): string {
  return text
    .replaceAll("\\", "\\\\")
    .replace(
      /\[\[|%%|==|\$|(?<=^|\s)#[\p{L}\p{N}_/-]+|\^[A-Za-z0-9-]+(?=\s*$)/gmu,
      (s) => `\\${s}`,
    );
}
/**
 * @sdpAnchor impl:protocol.vault-text
 * @sdpLabel renders checked mentions and escapes Obsidian syntax outside code spans
 * @sdpSatisfies spec:consumers.obsidian-vault.notes
 * @sdpComponent component:protocol.projections
 * @sdpRole codec
 */

export function createText(reader: Reader): {
  text: (value: string) => string;
  link: (id: string) => string;
} {
  const ids = new Set(reader.graph.nodes.map((n) => n.id));
  const link = (id: string): string => {
    const [base = "", subpath] = id.split("#");
    if (!ids.has(base) || (subpath !== undefined && !reader.resolveEntryAddress(id).resolves))
      return code(id);
    return `[[${notePath(base)}${subpath === undefined ? "" : `#^${subpath.replace(".", "-")}`}|${id}]]`;
  };
  const plain = (value: string): string => {
    let rendered = "",
      at = 0;
    for (const token of mentionTokens(value)) {
      const start = value.indexOf(token, at);
      if (start < 0) continue;
      rendered += escapeText(value.slice(at, start));
      const [base = "", subpath] = token.split("#");
      rendered +=
        ids.has(base) && (subpath === undefined || reader.resolveEntryAddress(token).resolves)
          ? link(token)
          : escapeText(token);
      at = start + token.length;
    }
    return rendered + escapeText(value.slice(at));
  };
  const text = (value: string): string =>
    mapCodeSpans(value, plain, (span) => {
      const tokens = mentionTokens(span);
      const token = tokens[0];
      return token !== undefined &&
        tokens.length === 1 &&
        token === span &&
        link(token) !== code(token)
        ? link(token)
        : code(span);
    });
  return { text, link };
}
export function properties(values: Readonly<Record<string, unknown>>): string {
  return [
    "---",
    ...Object.entries(values)
      .filter(([, v]) => v !== undefined)
      .map(([key, value]) => `${key}: ${JSON.stringify(value)}`),
    "---",
    "",
  ].join("\n");
}
export function banner(kind: string, file: string): string {
  return `> [!info] Generated by \`sdp vault\` from the graph. Edit the ${kind} ${code(file)}, never this note: a regeneration refuses while a note it wrote has changed.`;
}
